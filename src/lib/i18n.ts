const DICTS: Record<Locale, Dict> = { en, fr, ar };

export type Vars = Record<string, string | number>;

export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const raw = DICTS[locale][key] ?? en[key];
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : raw;
}

export type T = (key: MessageKey, vars?: Vars) => string;
export const makeT =
  (locale: Locale): T =>
  (key, vars) =>
    translate(locale, key, vars);

/** "12 min ago" style, localized. */
export function agoText(t: T, mins: number) {
  if (mins < 1) return t("time.justNow");
  if (mins < 60) return t("time.min", { n: mins });
  return t("time.hour", { n: Math.floor(mins / 60) });
}

/** Numbers stay Western digits in all three languages, as on Algerian receipts. */
export const intlLocale = (l: Locale) => (l === "ar" ? "ar-DZ-u-nu-latn" : l === "fr" ? "fr-DZ" : "en-GB");

/** "08:00 to 20:00" or "Open 24/7", localized. */
export function hoursText(t: T, p: { opens: number; closes: number }) {
  const hhmm = (m: number) => (m >= 1440 ? "24:00" : `${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`);
  if (p.opens === 0 && p.closes === 1440) return t("hours.always");
  return t("hours.range", { from: hhmm(p.opens), to: hhmm(p.closes) });
}

